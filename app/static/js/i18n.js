/* 词典未命中就退回中文，绝不产生空标签；需要新文案时先加中文再补 EN */
export function missingKeys(root){
  const out=[];
  const w=document.createTreeWalker(root||document.body,NodeFilter.SHOW_TEXT);
  let n;
  while((n=w.nextNode())){
    const host=n.parentNode;
    if(!host||host.nodeType!==1||/^(SCRIPT|STYLE|TITLE)$/.test(host.tagName)||
       (host.closest&&host.closest("[data-notr]")))continue;
    const key=norm(n.nodeValue);
    if(!key||/[一-鿿]/.test(key)===false)continue;
    if(!Object.prototype.hasOwnProperty.call(EN,key))out.push(key);
  }
  return out;
}
